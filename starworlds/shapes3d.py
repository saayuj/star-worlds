"""
Convex 3-D obstacle shapes described by their support function.

Each shape exposes the interface used by ``create_star_world_3d``
(``dim``, ``center``, ``polygon_approximation``, ``contains``) plus

  support(u)          — support point in unit direction u
  signed_distance(p)  — exact signed distance (negative inside)
  inflated(dr)        — Minkowski sum with a ball of radius dr
  bounding_radius()   — radius of the smallest center-based bounding sphere

Surface samples for the star-world construction are generated by
evaluating the support function on a Fibonacci set of directions, which
gives exact boundary points of the (possibly inflated) convex set. The
convex hull of those points is the polytope approximation used by
Algorithm 2.
"""

from __future__ import annotations

import numpy as np


def fibonacci_directions(n: int) -> np.ndarray:
    """n roughly-uniform unit vectors on S^2."""
    idx = np.arange(n) + 0.5
    phi = np.arccos(1.0 - 2.0 * idx / n)
    theta = np.pi * (1.0 + np.sqrt(5.0)) * idx
    return np.column_stack([np.sin(phi) * np.cos(theta),
                            np.sin(phi) * np.sin(theta),
                            np.cos(phi)])


def quat_to_matrix(q) -> np.ndarray:
    x, y, z, w = q
    return np.array([
        [1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
        [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
        [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)],
    ])


class ConvexShape3D:
    """Base class; subclasses implement _support_local and _sd_local."""

    dim = 3
    is_convex = True
    kind = "convex"

    def __init__(self, center, R=None, inflation: float = 0.0):
        self.center = np.asarray(center, dtype=float)
        self.R = np.eye(3) if R is None else np.asarray(R, dtype=float)
        self.inflation = float(inflation)

    # -- interface -----------------------------------------------------
    def support(self, u: np.ndarray) -> np.ndarray:
        u = np.atleast_2d(u)
        ul = u @ self.R                       # world -> local (R^T u)
        s = self._support_local(ul) @ self.R.T
        return self.center + s + self.inflation * u

    def polygon_approximation(self, n: int = 64) -> np.ndarray:
        return self.support(fibonacci_directions(n))

    def signed_distance(self, p) -> np.ndarray:
        p = np.atleast_2d(np.asarray(p, dtype=float))
        pl = (p - self.center) @ self.R
        return self._sd_local(pl) - self.inflation

    def contains(self, point) -> bool:
        return bool(self.signed_distance(point)[0] <= 0.0)

    def bounding_radius(self) -> float:
        return self._bounding_radius_local() + self.inflation

    def _copy(self):
        import copy
        s = copy.copy(self)
        s.__dict__.pop('_hull_eq_cache', None)   # geometry caches are invalid
        return s

    def inflated(self, dr: float) -> "ConvexShape3D":
        s = self._copy()
        s.inflation = self.inflation + float(dr)
        return s

    def moved(self, center, R=None) -> "ConvexShape3D":
        s = self._copy()
        s.center = np.asarray(center, dtype=float)
        if R is not None:
            s.R = np.asarray(R, dtype=float)
        return s


class Sphere3D(ConvexShape3D):
    kind = "sphere"

    def __init__(self, center, radius, R=None, inflation=0.0):
        super().__init__(center, R, inflation)
        self.radius = float(radius)

    def _support_local(self, ul):
        return self.radius * ul

    def _sd_local(self, pl):
        return np.linalg.norm(pl, axis=1) - self.radius

    def _bounding_radius_local(self):
        return self.radius


class Box3D(ConvexShape3D):
    kind = "box"

    def __init__(self, center, half_extents, R=None, inflation=0.0):
        super().__init__(center, R, inflation)
        self.h = np.asarray(half_extents, dtype=float)

    def _support_local(self, ul):
        return self.h * np.where(ul >= 0, 1.0, -1.0)

    def _sd_local(self, pl):
        q = np.abs(pl) - self.h
        outside = np.linalg.norm(np.maximum(q, 0.0), axis=1)
        inside = np.minimum(np.max(q, axis=1), 0.0)
        return outside + inside

    def _bounding_radius_local(self):
        return float(np.linalg.norm(self.h))


class Cylinder3D(ConvexShape3D):
    """Cylinder with local z axis, radius r and half-height hh."""
    kind = "cylinder"

    def __init__(self, center, radius, half_height, R=None, inflation=0.0):
        super().__init__(center, R, inflation)
        self.radius = float(radius)
        self.hh = float(half_height)

    def _support_local(self, ul):
        xy = ul[:, :2]
        nxy = np.linalg.norm(xy, axis=1, keepdims=True)
        rad = np.where(nxy > 1e-12, xy / np.maximum(nxy, 1e-12), 0.0) * self.radius
        z = self.hh * np.where(ul[:, 2:3] >= 0, 1.0, -1.0)
        return np.hstack([rad, z])

    def _sd_local(self, pl):
        d_r = np.linalg.norm(pl[:, :2], axis=1) - self.radius
        d_z = np.abs(pl[:, 2]) - self.hh
        q = np.column_stack([d_r, d_z])
        outside = np.linalg.norm(np.maximum(q, 0.0), axis=1)
        inside = np.minimum(np.max(q, axis=1), 0.0)
        return outside + inside

    def _bounding_radius_local(self):
        return float(np.hypot(self.radius, self.hh))
